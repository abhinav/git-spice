#!/usr/bin/env bash

set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
design_dir="$script_dir/../design"
readme="$design_dir/README.md"
output="$(mktemp)"
trap 'rm -f "$output"' EXIT

{
    echo "# Architecture decision records"
    echo
    echo "<!-- Generated by ../tools/update-adr-table.sh. -->"
    echo
    echo "| Date | Decision |"
    echo "| --- | --- |"

    adrs=("$design_dir"/[0-9]*.md)
    for ((i = ${#adrs[@]} - 1; i >= 0; i--)); do
        adr="${adrs[i]}"
        filename="${adr##*/}"
        date="${filename:0:10}"
        decision="$(awk '/^# / { sub(/^# /, ""); print; exit }' "$adr")"
        printf '| %s | [%s](%s) |\n' "$date" "$decision" "$filename"
    done
} >"$output"

if [[ "${1:-}" == "--diff" ]]; then
    diff -u "$readme" "$output"
else
    mv "$output" "$readme"
fi
